"""Markdown audit report generator for DocuDoctor."""

from datetime import datetime
from typing import Any, Dict

from docudoctor.languages.base import LanguageAuditResult


def generate_markdown_report(
    result: LanguageAuditResult,
    filename: str = "main.py",
    language: str = "python",
) -> str:
    """Generate a comprehensive GitHub-flavored Markdown audit report."""
    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    # Severity counters
    errors = sum(1 for i in result.issues if i.severity == "ERROR")
    warnings = sum(1 for i in result.issues if i.severity == "WARNING")
    infos = sum(1 for i in result.issues if i.severity == "INFO")

    lines = [
        f"# 🩺 DocuDoctor Code Health & Audit Report",
        f"",
        f"> **File:** `{filename}` &nbsp;|&nbsp; **Language:** `{language.upper()}` &nbsp;|&nbsp; **Generated:** `{now_str}`",
        f"",
        f"---",
        f"",
        f"## 📊 Executive Summary",
        f"",
        f"| Metric | Result | Health Status |",
        f"| :--- | :---: | :--- |",
        f"| **Overall Documentation Score** | **{result.score}%** | **Grade {result.grade} ({result.label})** |",
        f"| **Maintainability Index** | **{result.maintainability_index} / 100** | Grade {result.maintainability_grade} |",
        f"| **Average Cyclomatic Complexity** | **{result.avg_complexity}** | {'🟢 Low Risk' if result.avg_complexity <= 5 else ('🟡 Moderate' if result.avg_complexity <= 10 else '🔴 High Risk')} |",
        f"| **Functions Documented** | `{result.documented_functions} / {result.total_functions}` | {round((result.documented_functions / max(1, result.total_functions)) * 100)}% coverage |",
        f"| **Typed Return Signatures** | `{result.typed_returns} / {result.total_functions}` | {round((result.typed_returns / max(1, result.total_functions)) * 100)}% coverage |",
        f"| **Total Classes / Structs** | `{result.total_classes}` | Audited |",
        f"",
        f"### 🛡️ Defect Severity Breakdown",
        f"- 🔴 **Errors (Missing Public Docs):** `{errors}`",
        f"- 🟡 **Warnings (Type hints / Mutable defaults / Complexity):** `{warnings}`",
        f"- 🔵 **Info / Style Suggestions:** `{infos}`",
        f"",
        f"---",
        f"",
        f"## 🔍 Detected Issues & Recommendations",
        f"",
    ]

    if not result.issues:
        lines.append("✨ **No documentation or syntax defects detected! Clean codebase.**\n")
    else:
        lines.append("| Line | Entity | Type | Severity | Message & Recommendation |")
        lines.append("| :---: | :--- | :--- | :---: | :--- |")
        for iss in result.issues:
            sev_badge = "🔴 ERROR" if iss.severity == "ERROR" else ("🟡 WARNING" if iss.severity == "WARNING" else "🔵 INFO")
            msg_clean = iss.message.replace("|", "/")
            rec_clean = iss.recommendation.replace("|", "/")
            lines.append(
                f"| `{iss.line}` | `{iss.entity}` ({iss.entity_type}) | `{iss.issue_type}` | {sev_badge} | {msg_clean}<br>💡 *{rec_clean}* |"
            )
        lines.append("")

    lines.extend([
        f"---",
        f"",
        f"## 🧩 Function & Entity Inventory",
        f"",
        f"| Entity Name | Type | Line | Complexity | Documented | Return Type |",
        f"| :--- | :---: | :---: | :---: | :---: | :--- |",
    ])

    if not result.entities:
        lines.append("| *(None found)* | - | - | - | - | - |")
    else:
        for ent in result.entities:
            has_doc = "✅ Yes" if (ent.docstring and ent.docstring.strip()) else "❌ Missing"
            ret_display = f"`{ent.return_type}`" if ent.return_type else "*None / Untyped*"
            lines.append(
                f"| `{ent.name}` | `{ent.entity_type}` | `{ent.line_start}` | `{ent.complexity}` | {has_doc} | {ret_display} |"
            )

    lines.extend([
        f"",
        f"---",
        f"",
        f"### ⚡ How to Auto-Heal this Code",
        f"Run DocuDoctor directly in your terminal to automatically inject docstrings, fix mutable defaults, and add type hints:",
        f"```bash",
        f"docudoctor fix {filename} --style google",
        f"```",
        f"",
        f"*Report generated by [DocuDoctor](https://github.com/prasunkrghosh-18/docudoctor) v0.2.0 • Created by [@prasunkrghosh-18](https://github.com/prasunkrghosh-18)*",
    ])

    return "\n".join(lines)
